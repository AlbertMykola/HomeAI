"""Apply hand-crafted PL / pt-BR / RU strings (same approach as da/de/es/fr)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "HomeAI" / "Resources"
EN = RES / "en.lproj" / "Localizable.strings"


def parse_strings(path: Path) -> dict[str, str]:
    content = path.read_text(encoding="utf-8")
    pattern = re.compile(r'"((?:\\.|[^"\\])*)"\s*=\s*"((?:\\.|[^"\\])*)"\s*;', re.MULTILINE)
    d: dict[str, str] = {}
    for m in pattern.finditer(content):
        v = m.group(2).replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
        d[m.group(1)] = v
    return d


def build_locale(locale: str, existing: dict[str, str], new: dict[str, str], full_2d: str, choc: tuple[str, str]) -> int:
    en_content = EN.read_text(encoding="utf-8")
    merged = {**existing, **new}
    pattern = re.compile(r'^("((?:\\.|[^"\\])*)"\s*=\s*")((?:\\.|[^"\\])*)(";\s*)$', re.MULTILINE)

    def repl(m: re.Match[str]) -> str:
        key = m.group(2)
        if not key.strip():
            return m.group(0)
        val = merged.get(key, m.group(3))
        val = val.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        return f'"{key}" = "{val}";'

    out = pattern.sub(repl, en_content)
    legacy = [
        "Transform your space — snap a room and let AI do the rest.",
        "Upload a photo of your home, choose your style and let AI redesign your facade!",
        "Take a photo, and let AI reveal your garden's full potential.",
        "Bring your ideas to life — select a reference style and discover a new vibe with AI.",
        "Choose an object and let AI replace it instantly.",
        "Replace objects in your photo with AI-powered precision.",
        "Try new flooring in seconds. AI instantly detects and replaces your floor.",
        "Reimagine your walls with AI. Instantly preview colors, textures, and finishes in your space.",
    ]
    out += "\n// Legacy home descriptions\n"
    for k in legacy:
        v = merged.get(k) or existing.get(k)
        if v:
            vk = v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            out += f'"{k}" = "{vk}";\n'
    if '"Cyberpunk"' not in out:
        out = out.replace(choc[0], choc[1])
    out = re.sub(
        r'("Full 2D floor plan with every room clearly visible\.\\nSharp, high-quality image with clean lines\.\\nSimple layout without extra notes or markings\.\\nAvoid blurry, cropped, or low-resolution plans\." = ")[^"]*(";\s*)',
        lambda m: m.group(1) + full_2d + m.group(2),
        out,
    )
    path = RES / f"{locale}.lproj" / "Localizable.strings"
    path.write_text(out, encoding="utf-8")
    en = parse_strings(EN)
    loc = parse_strings(path)
    return len([k for k in en if k.strip() and k not in loc])


