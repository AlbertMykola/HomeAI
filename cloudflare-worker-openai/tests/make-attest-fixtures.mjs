// Builds an App Attest-shaped attestation signed by a throwaway test CA (NOT Apple's), for unit tests.
// Run by tests/attest.test.js → tests/fixtures/attest.json (gitignored).
import { execFileSync } from "node:child_process"
import { createHash, createPrivateKey, createPublicKey } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const dir = mkdtempSync(join(tmpdir(), "attest-fixtures-"))
const ssl = (...args) => execFileSync("openssl", args, { cwd: dir, stdio: ["ignore", "pipe", "pipe"] })
const sha256 = (data) => createHash("sha256").update(data).digest()

const appId = "TESTTEAM01.com.example.attest"
const challenge = "fixture-challenge"

try {
	ssl("ecparam", "-name", "secp384r1", "-genkey", "-noout", "-out", "root.key")
	ssl("req", "-new", "-x509", "-sha384", "-key", "root.key", "-subj", "/CN=Test Root", "-days", "36500", "-out", "root.pem")
	ssl("ecparam", "-name", "secp384r1", "-genkey", "-noout", "-out", "ca.key")
	ssl("req", "-new", "-sha384", "-key", "ca.key", "-subj", "/CN=Test CA", "-out", "ca.csr")
	writeFileSync(join(dir, "ca.ext"), "basicConstraints=critical,CA:true\n")
	ssl("x509", "-req", "-sha384", "-in", "ca.csr", "-CA", "root.pem", "-CAkey", "root.key", "-set_serial", "2",
		"-days", "36500", "-extfile", "ca.ext", "-out", "ca.pem")

	ssl("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "leaf.key")
	const leafKey = createPrivateKey(readFileSync(join(dir, "leaf.key")))
	const spki = createPublicKey(leafKey).export({ format: "der", type: "spki" })
	const point = spki.subarray(spki.length - 65)
	const keyId = sha256(point)

	const authData = Buffer.concat([
		sha256(Buffer.from(appId)),
		Buffer.from([0x40]),
		Buffer.from([0, 0, 0, 0]),
		Buffer.from("appattestdevelop"),
		Buffer.from([0, 32]),
		keyId,
		Buffer.from([0xa0]), // COSE key (not parsed by the verifier)
	])
	const nonce = sha256(Buffer.concat([authData, sha256(Buffer.from(challenge))]))
	writeFileSync(join(dir, "leaf.ext"), `1.2.840.113635.100.8.2=DER:3024a1220420${nonce.toString("hex")}\n`)
	ssl("req", "-new", "-sha256", "-key", "leaf.key", "-subj", "/CN=leaf", "-out", "leaf.csr")
	ssl("x509", "-req", "-sha256", "-in", "leaf.csr", "-CA", "ca.pem", "-CAkey", "ca.key", "-set_serial", "3",
		"-days", "36500", "-extfile", "leaf.ext", "-out", "leaf.pem")
	const der = (name) => ssl("x509", "-in", name, "-outform", "DER")

	const attestation = cbor({
		fmt: "apple-appattest",
		attStmt: { x5c: [der("leaf.pem"), der("ca.pem")], receipt: Buffer.from("receipt") },
		authData,
	})

	mkdirSync(join(here, "fixtures"), { recursive: true })
	writeFileSync(join(here, "fixtures", "attest.json"), JSON.stringify({
		note: "Throwaway test CA and key, generated by make-attest-fixtures.mjs. Not Apple's, not used anywhere real.",
		appId,
		challenge,
		keyId: keyId.toString("base64"),
		attestation: attestation.toString("base64"),
		rootPem: readFileSync(join(dir, "root.pem"), "utf8"),
		leafPrivateKeyPem: leafKey.export({ format: "pem", type: "pkcs8" }),
	}, null, "\t") + "\n")
	console.log("wrote tests/fixtures/attest.json")
} finally {
	rmSync(dir, { recursive: true, force: true })
}

function cbor(value) {
	const head = (major, length) => {
		if (length < 24) return Buffer.from([(major << 5) | length])
		if (length < 256) return Buffer.from([(major << 5) | 24, length])
		if (length < 65536) return Buffer.from([(major << 5) | 25, length >> 8, length & 0xff])
		const out = Buffer.alloc(5)
		out[0] = (major << 5) | 26
		out.writeUInt32BE(length, 1)
		return out
	}
	if (Buffer.isBuffer(value)) return Buffer.concat([head(2, value.length), value])
	if (typeof value === "string") {
		const bytes = Buffer.from(value)
		return Buffer.concat([head(3, bytes.length), bytes])
	}
	if (Array.isArray(value)) return Buffer.concat([head(4, value.length), ...value.map(cbor)])
	const entries = Object.entries(value)
	return Buffer.concat([head(5, entries.length), ...entries.flatMap(([k, v]) => [cbor(k), cbor(v)])])
}
